import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FEED_PATH = resolve(ROOT, 'backend/storage/feed/feed-manifest.v1.json');
const CATALOG_PATH = resolve(ROOT, 'backend/storage/catalog/structured-assets.v1.json');
const OUTPUT_PATH = resolve(ROOT, 'web/prototype/pages/shared/library-assets.generated.js');

export function buildFrontendAssetRecords(feed, catalog) {
  const detailById = new Map((catalog.assets || []).map((asset) => [asset.asset_id, asset]));
  return (feed.canonical_assets || []).filter((asset) => asset.status === 'ready').map((asset) => {
    const detail = detailById.get(asset.asset_id);
    const source = asset.source || {};
    const media = asset.media || {};
    const labels = asset.labels || {};
    return {
      asset_id: asset.asset_id,
      name: asset.name,
      type: { category: labels.category || '', subcategory: labels.sub || labels.subcategory || '' },
      labels: {
        colors: labels.colors || [],
        materials: labels.materials || [],
        styles: labels.styles || [],
      },
      size_status: detail?.dimensions?.status || 'unknown',
      physical_size_m: detail?.dimensions?.physical_m || { width: null, height: null, depth: null },
      dimensions_model_unit: detail?.dimensions?.model_unit || null,
      source_type: source.source_type || 'platform',
      source_label: source.source_label || null,
      source_url: source.source_url || null,
      thumbnail: media.thumbnail || null,
      frame_url: media.context || null,
      model_url: media.model_3d || null,
      video_url: media.video || null,
      video_id: source.video_id || null,
      representative_sec: source.t_best ?? null,
      tag_provenance: asset.tag_provenance || null,
    };
  });
}

if (resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) {
  const option = (name, fallback) => { const index = process.argv.indexOf(name); return index >= 0 && process.argv[index + 1] ? resolve(process.argv[index + 1]) : fallback; };
  const feedPath = option('--feed', FEED_PATH);
  const catalogPath = option('--catalog', CATALOG_PATH);
  const outputPath = option('--output', OUTPUT_PATH);
  const feed = JSON.parse(readFileSync(feedPath, 'utf8'));
  const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));
  const records = buildFrontendAssetRecords(feed, catalog);
  const banner = `// AUTO-GENERATED by tools/sync-frontend-asset-catalog.mjs — 请勿手改。\n`
    + `// 源：backend/storage/feed/feed-manifest.v1.json（${records.length} 件，content_version=${feed.content_version}）\n`
    + `// 尺寸详情：backend/storage/catalog/structured-assets.v1.json；unknown 不代表真实物理尺寸。\n`;
  writeFileSync(outputPath, `${banner}export const BACKEND_ASSETS = ${JSON.stringify(records)};\n`);
  console.log(JSON.stringify({ output: outputPath, records: records.length }, null, 2));
}
